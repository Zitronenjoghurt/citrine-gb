use std::sync::OnceLock;

pub(super) fn char_of(unit: u16) -> Option<char> {
    let index = RUNS
        .partition_point(|&(start, _)| start <= unit)
        .checked_sub(1)?;
    let (start, chars) = RUNS[index];
    chars.chars().nth(usize::from(unit - start))
}

pub(super) fn unit_of(c: char, full_width: bool) -> Option<u16> {
    static UNITS: OnceLock<Vec<(char, u16)>> = OnceLock::new();
    let units = UNITS.get_or_init(|| {
        let mut units: Vec<(char, u16)> = RUNS
            .iter()
            .flat_map(|&(start, chars)| chars.chars().zip(start..))
            .collect();
        units.sort_by_key(|&(c, unit)| (c, unit));
        units
    });
    let first = units.partition_point(|&(other, _)| other < c);
    let end = units.partition_point(|&(other, _)| other <= c);
    let index = if full_width {
        first
    } else {
        end.checked_sub(1)?
    };
    (first < end).then(|| units[index].1)
}

